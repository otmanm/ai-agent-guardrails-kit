#!/bin/bash
# Phase 0 benchmark: run only the tests that need no paid LLM, no Docker, and no
# large downloads. It records what was actually run. Everything else in MATRIX.md
# is labeled sourced, inferred, or not-runnable, with reproduction steps.
#
# Run: bash benchmark/run-local.sh
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/LOCAL-RESULTS.md"

{
  echo "# Local benchmark results (what was actually run)"
  echo
  echo "Generated by \`benchmark/run-local.sh\`. These are the cells that can be measured here without money, Docker, or large downloads."
  echo
} > "$OUT"

echo "== Phase 0 local benchmark =="

# 1. The kit's application guard layer vs the five paths (measured elsewhere, re-run here for one source of truth)
echo "-- kit guard layer (re-running the attack matrix) --"
if bash "$HERE/../tests/attack-matrix/run-matrix.sh" >/dev/null 2>&1; then
  echo "- **Kit guard layer**: MEASURED. \`tests/attack-matrix/run-matrix.sh\` passes; see tests/attack-matrix/RESULTS.md for the per-path blocked/allowed table." >> "$OUT"
  echo "kit guard matrix: OK"
else
  echo "- **Kit guard layer**: matrix run FAILED, investigate." >> "$OUT"
  echo "kit guard matrix: FAILED"
fi

# 2. open-dynamic-workflows isolation: node:vm boundary (measured, no deps)
echo "-- open-dynamic-workflows isolation (node:vm) --"
if command -v node >/dev/null 2>&1; then
  NODE_V="$(node --version)"
  DEMO="$(node "$HERE/vm-isolation-demo.js" 2>&1)"
  echo "$DEMO" | sed 's/^/   /'
  {
    echo "- **open-dynamic-workflows isolation (node:vm)**: MEASURED on node $NODE_V."
    echo "  \`\`\`"
    echo "$DEMO" | sed 's/^/  /'
    echo "  \`\`\`"
  } >> "$OUT"
else
  echo "- **open-dynamic-workflows isolation**: NOT-RUN (node not installed here). Install Node and run \`node benchmark/vm-isolation-demo.js\`." >> "$OUT"
  echo "node not present, skipped vm demo"
fi

{
  echo
  echo "Everything not listed above (Claude Dynamic Workflows full pipeline, DannyMac180's playbook, OpenHands sandbox) is **not-runnable here**: it needs a paid LLM, Docker, or large downloads. See MATRIX.md for the sourced and inferred assessment of those, each with the exact command to run it yourself."
} >> "$OUT"

echo "----"
echo "Local results written to benchmark/LOCAL-RESULTS.md"
exit 0
